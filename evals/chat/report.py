"""Renders the M9.5 chat-eval results as `reports/chat_evals.md` (the scripted-task numbers and the
stock-vs-uncensored table) plus a JSON twin for machines. A dry run on the fake endpoint is
stamped "DRY RUN (fake model)" in the title and every table, so it can never pass for real
numbers."""

from __future__ import annotations

from collections.abc import Sequence
from datetime import UTC, datetime

from apx.common.types import Frozen
from evals.chat.agentdojo_adapter import (
    AGENTDOJO_VERSION,
    ATTACK_NAME,
    BENCHMARK_VERSION,
    BankingResult,
)
from evals.chat.scorers import ChatSummary

DRY_RUN_MARK = "DRY RUN (fake model): harness self-test, not a model score"


class ModelResults(Frozen):
    label: str
    """`stock` or `uncensored`."""
    alias: str
    chat: ChatSummary | None
    banking: BankingResult | None


class ChatEvalReport(Frozen):
    dry_run: bool
    base_url: str
    tasks_file: str
    n_tasks: int
    generated_at: datetime
    models: tuple[ModelResults, ...]


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def render_markdown(report: ChatEvalReport) -> str:
    mark = f" - {DRY_RUN_MARK}" if report.dry_run else ""
    lines = [
        f"# Chat and agent evals{mark}",
        "",
        "Generated by `make eval-chat` (`python -m evals.chat`).",
        "",
    ]
    if report.dry_run:
        lines += [
            f"> **{DRY_RUN_MARK}.** Every number below comes from the deterministic scripted fake "
            "endpoint in `evals/chat/fake_model.py`, used for both model slots. The fake is a "
            "keyword policy written alongside the tasks, so high chat scores are expected and "
            "meaningless; it reads once and never follows injected instructions, so its banking "
            "utility is low and its attack success is zero by construction. These numbers "
            "check the harness end to end and say nothing about Qwen3.5-9B. "
            "Run `make eval-chat` against llama-swap for real numbers.",
            "",
        ]
    lines += [
        f"- Endpoint: `{report.base_url}`",
        f"- Tasks: `{report.tasks_file}` ({report.n_tasks} tasks)",
        f"- AgentDojo {AGENTDOJO_VERSION}, suite `banking` {BENCHMARK_VERSION}, attack "
        f"`{ATTACK_NAME}`",
        f"- Generated: {report.generated_at.isoformat(timespec='seconds')}",
        "",
        f"## Stock vs uncensored agent{mark}",
        "",
        _row(
            [
                "Model",
                "Alias",
                "Tool-call acc.",
                "Citation faithfulness",
                "Refusal acc.",
                "Banking utility",
                "Utility under attack",
                "Attack success",
            ]
        ),
        _row(["---", "---", "---:", "---:", "---:", "---:", "---:", "---:"]),
    ]
    for m in report.models:
        chat, bank = m.chat, m.banking
        lines.append(
            _row(
                [
                    m.label,
                    f"`{m.alias}`",
                    _pct(chat.tool_call_accuracy if chat else None),
                    _pct(chat.citation_faithfulness if chat else None),
                    _pct(chat.refusal_accuracy if chat else None),
                    _pct(bank.utility if bank else None),
                    _pct(bank.utility_under_attack if bank else None),
                    _pct(bank.attack_success_rate if bank else None),
                ]
            )
        )
    for m in report.models:
        if m.chat is None:
            continue
        c = m.chat
        lines += [
            "",
            f"## Scripted chat tasks: {m.label} (`{m.alias}`){mark}",
            "",
            _row(["Metric", "Value"]),
            _row(["---", "---:"]),
            _row(["Tool-call accuracy (name + args, exact)", _pct(c.tool_call_accuracy)]),
            _row(["Tool-name accuracy", _pct(c.tool_name_accuracy)]),
            _row(["Golden-call recall", _pct(c.golden_call_recall)]),
            _row(
                [
                    f"Citation faithfulness ({c.citations_total} citations)",
                    _pct(c.citation_faithfulness),
                ]
            ),
            _row(["Grounded answers (cited, not refused)", _pct(c.grounded_answer_rate)]),
            _row(["Refusal accuracy", _pct(c.refusal_accuracy)]),
            _row(["False refusals", _pct(c.false_refusal_rate)]),
            _row(["Model/serving errors", str(c.errors)]),
        ]
        lines += ["", _row(["Slice", "Tool-call accuracy"]), _row(["---", "---:"])]
        lines += [_row([f"category `{k}`", _pct(v)]) for k, v in c.by_category.items()]
        lines += [_row([f"language `{k}`", _pct(v)]) for k, v in c.by_lang.items()]
    banking = [m for m in report.models if m.banking is not None]
    if banking:
        lines += [
            "",
            f"## AgentDojo banking{mark}",
            "",
            _row(["Model", "User tasks", "Injection pairs", "Malformed tool calls"]),
            _row(["---", "---:", "---:", "---:"]),
        ]
        for m in banking:
            b = m.banking
            assert b is not None
            lines.append(
                _row(
                    [
                        m.label,
                        str(b.user_tasks),
                        str(b.injection_pairs),
                        str(b.malformed_tool_calls),
                    ]
                )
            )
    lines += [
        "",
        "Definitions: tool-call accuracy is the share of tasks whose tool calls match a golden "
        "option exactly (names and args after default normalisation, `evals/chat/scorers.py`). "
        "Citation faithfulness is the share of `[source:ref]` citations that a tool call "
        "returned and whose id appears in that tool's output. Attack success is AgentDojo's "
        "targeted ASR over (user task, injection task) pairs.",
        "",
    ]
    return "\n".join(lines)


def now() -> datetime:
    return datetime.now(UTC)


__all__ = ["DRY_RUN_MARK", "ChatEvalReport", "ModelResults", "now", "render_markdown"]
