"""M6.4 injection-guard eval (PRD §10 M6.4): `build` writes the leak-checked guard dataset to
data/guard/, and `report` turns per-model score files (from `python -m ml.guard.infer`) into
reports/guard.md with P/R/F1, per-category recall on the adversarial suite and hard-negative FPR.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from ml.guard.metrics import BinaryMetrics, confusion, select_threshold

REPO_ROOT = Path(__file__).resolve().parents[1]
GUARD_DATA = REPO_ROOT / "data" / "guard"
REPORT_PATH = REPO_ROOT / "reports" / "guard.md"


@dataclass(frozen=True)
class ScoredRow:
    split: str
    label: int
    source: str
    group: str
    lang: str
    score: float


@dataclass(frozen=True)
class OperatingPoint:
    name: str
    threshold: float
    overall: BinaryMetrics
    hard_negative_fpr: float
    hard_negative_n: int
    per_category_recall: dict[str, tuple[float, int]]


@dataclass(frozen=True)
class ModelResult:
    model: str
    status: str  # "ok", or why there are no numbers (blocked / pending)
    points: tuple[OperatingPoint, ...] = ()


def load_scores(path: Path) -> list[ScoredRow]:
    rows: list[ScoredRow] = []
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                r = json.loads(line)
                rows.append(
                    ScoredRow(
                        r["split"],
                        int(r["label"]),
                        r["source"],
                        r["group"],
                        r["lang"],
                        float(r["score"]),
                    )
                )
    return rows


def operating_point(name: str, rows: Sequence[ScoredRow], threshold: float) -> OperatingPoint:
    """Test-split metrics at `threshold`."""
    test = [r for r in rows if r.split == "test"]
    overall = confusion([r.score for r in test], [r.label for r in test], threshold)
    hard = [r for r in test if r.source == "hard_negative"]
    hard_fp = sum(r.score >= threshold for r in hard)
    by_cat: dict[str, list[ScoredRow]] = defaultdict(list)
    for r in test:
        if r.source == "attack":
            by_cat[r.group].append(r)
    per_cat = {
        cat: (sum(r.score >= threshold for r in rs) / len(rs), len(rs))
        for cat, rs in sorted(by_cat.items())
    }
    return OperatingPoint(
        name=name,
        threshold=threshold,
        overall=overall,
        hard_negative_fpr=hard_fp / len(hard) if hard else 0.0,
        hard_negative_n=len(hard),
        per_category_recall=per_cat,
    )


def evaluate_model(
    model: str, rows: Sequence[ScoredRow], fixed: Sequence[tuple[str, float]] = ()
) -> ModelResult:
    """Cal-tuned operating point (max F1 on cal) plus any fixed thresholds, all scored on test."""
    cal = [r for r in rows if r.split == "cal"]
    tuned = select_threshold([r.score for r in cal], [r.label for r in cal])
    points = [operating_point(n, rows, t) for n, t in fixed]
    points.append(operating_point("cal-tuned (max F1)", rows, tuned))
    return ModelResult(model=model, status="ok", points=tuple(points))


def render_report(results: Sequence[ModelResult], dataset_counts: dict[str, dict[str, int]]) -> str:
    lines = [
        "# Injection guard: fine-tune vs baselines (M6.4)",
        "",
        "Generated by `python -m evals.guard report`. All numbers are on the **test** split;",
        "thresholds are chosen on **cal** only. Splits are dealt per template family, so no",
        "adversarial or hard-negative template appears in more than one split.",
        "",
        "## Dataset",
        "",
        "Hard negatives are hand-written invoice lines plus benign text mined from the",
        "`train` pool (never cal/test) of the two generated UAE invoice renders `data/uae` and",
        "`data/uae_stale_m2` (ADR-0012 §2): names, addresses, tax notes, EN/AR/bilingual lines",
        "and the clean Latin text layer (payment/IBAN lines, totals). Mined lines are grouped by",
        "template (first four words), so every numeric or wrapped variant sits in one split.",
        "",
        "| split | positives | negatives | hard negatives |",
        "|---|---:|---:|---:|",
    ]
    for split in ("train", "cal", "test"):
        c = dataset_counts.get(split, {})
        lines.append(f"| {split} | {c.get('pos', 0)} | {c.get('neg', 0)} | {c.get('hard', 0)} |")
    lines += [
        "",
        "## Overall",
        "",
        "| model | operating point | threshold | precision | recall | F1 | FPR | hard-neg FPR |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for res in results:
        if res.status != "ok":
            lines.append(f"| {res.model} | {res.status} | | | | | | |")
            continue
        for p in res.points:
            m = p.overall
            lines.append(
                f"| {res.model} | {p.name} | {p.threshold:.4f} | {m.precision:.3f} | "
                f"{m.recall:.3f} | {m.f1:.3f} | {m.fpr:.3f} | "
                f"{p.hard_negative_fpr:.3f} (n={p.hard_negative_n}) |"
            )
    scored = [r for r in results if r.status == "ok"]
    categories = sorted({c for r in scored for p in r.points for c in p.per_category_recall})
    if scored:
        lines += [
            "",
            "## Per-category recall on the adversarial suite (test families, cal-tuned)",
            "",
        ]
        lines.append("| category | n | " + " | ".join(r.model for r in scored) + " |")
        lines.append("|---|---:|" + "---:|" * len(scored))
        for cat in categories:
            cells = []
            n = 0
            for r in scored:
                recall, n_cat = r.points[-1].per_category_recall.get(cat, (float("nan"), 0))
                n = max(n, n_cat)
                cells.append(f"{recall:.3f}")
            lines.append(f"| {cat} | {n} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "Categories absent from the table have a single template family, which is dealt to",
        "train. `homoglyph_vendor` is excluded: its payload is a spoofed name, not instruction",
        "text, and SEC-15 (not the guard) is its control.",
        "",
        "## Reproduce",
        "",
        "1. `uv run python -m evals.datasets fetch --set prompt_injections` (pinned sha256)",
        "2. `uv run python -m evals.guard build`",
        "3. In the toolbox container: `python -m ml.guard.train` (GPU), then",
        "   `python -m ml.guard.infer --model-dir <ckpt> --out data/guard/scores/<name>.jsonl`",
        "4. `uv run python -m evals.guard report --scores <name>=<scores.jsonl> ...`",
        "",
    ]
    return "\n".join(lines)


def dataset_counts(data_dir: Path) -> dict[str, dict[str, int]]:
    counts: dict[str, dict[str, int]] = {}
    for split in ("train", "cal", "test"):
        c = {"pos": 0, "neg": 0, "hard": 0}
        path = data_dir / f"{split}.jsonl"
        if path.exists():
            for line in path.read_text(encoding="utf-8").splitlines():
                if line.strip():
                    r = json.loads(line)
                    c["pos" if r["label"] == 1 else "neg"] += 1
                    c["hard"] += r["source"] == "hard_negative"
        counts[split] = c
    return counts


def _build(data_dir: Path, invoice_dirs: Sequence[Path]) -> int:
    from evals.datasets.prompt_injections_fetcher import local_path
    from ml.guard.dataset import build_examples, write_splits
    from ml.guard.mine import mine_dataset

    data_root = REPO_ROOT / "data"
    train, test = local_path(data_root, "train"), local_path(data_root, "test")
    for p in (train, test):
        if not p.exists():
            raise FileNotFoundError(
                f"{p} missing; run `uv run python -m evals.datasets fetch --set prompt_injections`"
            )
    mined = [m for d in invoice_dirs for m in mine_dataset(d)]
    counts = write_splits(build_examples(train, test, mined=mined), data_dir)
    print(json.dumps(counts))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m evals.guard")
    sub = parser.add_subparsers(dest="command", required=True)
    b = sub.add_parser("build", help="write data/guard/{train,cal,test}.jsonl")
    b.add_argument("--data-dir", type=Path, default=GUARD_DATA)
    b.add_argument(
        "--invoices",
        type=Path,
        action="append",
        default=None,
        help="generated invoice set to mine hard negatives from (its train pool only)",
    )
    r = sub.add_parser("report", help="write reports/guard.md from score files")
    r.add_argument("--data-dir", type=Path, default=GUARD_DATA)
    r.add_argument("--scores", action="append", default=[], metavar="MODEL=PATH")
    r.add_argument("--fixed", action="append", default=[], metavar="MODEL=NAME:THRESHOLD")
    r.add_argument("--status", action="append", default=[], metavar="MODEL=STATUS")
    r.add_argument("--out", type=Path, default=REPORT_PATH)
    args = parser.parse_args(argv)

    if args.command == "build":
        dirs = args.invoices or [REPO_ROOT / "data" / "uae", REPO_ROOT / "data" / "uae_stale_m2"]
        return _build(args.data_dir, dirs)

    fixed: dict[str, list[tuple[str, float]]] = defaultdict(list)
    for spec in args.fixed:
        model, rest = spec.split("=", 1)
        name, value = rest.rsplit(":", 1)
        fixed[model].append((name, float(value)))
    results: list[ModelResult] = []
    for spec in args.status:
        model, status = spec.split("=", 1)
        results.append(ModelResult(model=model, status=status))
    for spec in args.scores:
        model, path = spec.split("=", 1)
        results.append(evaluate_model(model, load_scores(Path(path)), fixed[model]))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        render_report(results, dataset_counts(args.data_dir)), encoding="utf-8", newline="\n"
    )
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
