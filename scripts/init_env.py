"""Creates `.env` from `.env.example` on first run and fills every shared secret the stack needs
(`API_JWT_SECRET`, `POSTGRES_PASSWORD`, `AGENT_RO_PASSWORD`) that is missing or empty, so `make up`
needs no manual setup and no install runs on a committed default.
An existing value is never changed and no value is ever printed; only key names are reported."""

from __future__ import annotations

import os
import secrets
import sys
import tempfile
from pathlib import Path

GENERATED = ("API_JWT_SECRET", "POSTGRES_PASSWORD", "AGENT_RO_PASSWORD", "PARSE_SERVICE_TOKEN")
"""Secrets `infra/compose.yaml` refuses to start without (`${VAR:?...}`). Generated values are
URL-safe base64, so they also embed verbatim in a database URL."""

_APPEND_HEADER = (
    "# Generated by scripts/init_env.py (never printed; rotate with `make rotate-db-password`)"
)


def _key_of(line: str) -> str | None:
    """The key a dotenv line assigns (`KEY=...` or `export KEY=...`), or None for comments,
    blanks and anything without `=`. Looks only at the text before the first `=`."""
    stripped = line.strip()
    if not stripped or stripped.startswith("#"):
        return None
    key, sep, _ = stripped.partition("=")
    if not sep:
        return None
    key = key.strip()
    if key.startswith("export "):
        key = key[len("export ") :].strip()
    return key or None


def _is_empty_assignment(line: str) -> bool:
    """True when the assigned value is blank or an empty quoted string (`""`, `''`). Only ever
    returns a bool, so callers cannot leak the value."""
    _, _, value = line.partition("=")
    return not value.strip().strip("'\"").strip()


def secret_key_status(env: Path) -> dict[str, bool]:
    """Maps each `GENERATED` key found in `env` to whether it has a non-empty value. The
    values themselves never leave this function."""
    status: dict[str, bool] = {}
    for line in env.read_text(encoding="utf-8").splitlines():
        key = _key_of(line)
        if key in GENERATED:
            status[key] = status.get(key, False) or not _is_empty_assignment(line)
    return status


def _secret() -> str:
    return secrets.token_urlsafe(32)


def _fill_empty_lines(text: str, names: set[str]) -> tuple[str, set[str]]:
    """Replaces the first empty `NAME=` line for each of `names` with a freshly generated value
    and returns the new text plus the names it filled; every other line (and its line ending) is
    kept byte for byte."""
    out: list[str] = []
    filled: set[str] = set()
    for line in text.splitlines(keepends=True):
        key = _key_of(line)
        if key is not None and key in names - filled and _is_empty_assignment(line):
            ending = line[len(line.rstrip("\r\n")) :] or "\n"
            line = f"{key}={_secret()}{ending}"
            filled.add(key)
        out.append(line)
    return "".join(out), filled


def _write_private(path: Path, text: str) -> None:
    """Atomically replaces `path` (owner-only permissions where the OS supports them), so an
    interrupted run never leaves a truncated `.env`."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".env.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _append(path: Path, names: list[str]) -> None:
    """Appends `NAME=<generated>` for each missing key without reading any existing value; only
    the file's last byte is inspected, to start on a fresh line."""
    needs_newline = False
    if path.stat().st_size > 0:
        with path.open("rb") as handle:
            handle.seek(-1, os.SEEK_END)
            needs_newline = handle.read(1) != b"\n"
    block = "".join(f"{name}={_secret()}\n" for name in names)
    with path.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(("\n" if needs_newline else "") + _APPEND_HEADER + "\n" + block)


def init_env(root: Path) -> list[str]:
    """Returns the keys it generated, in `GENERATED` order. Raises FileNotFoundError when neither
    `.env` nor `.env.example` exists."""
    env = root / ".env"
    if not env.exists():
        template = (root / ".env.example").read_text(encoding="utf-8")
        present = {_key_of(line) for line in template.splitlines()}
        text, filled = _fill_empty_lines(template, set(GENERATED))
        missing = [name for name in GENERATED if name not in present]
        if missing:
            text += ("" if text.endswith("\n") or not text else "\n") + _APPEND_HEADER + "\n"
            text += "".join(f"{name}={_secret()}\n" for name in missing)
        _write_private(env, text)
        return [name for name in GENERATED if name in filled or name in missing]

    status = secret_key_status(env)
    empty = {name for name, has_value in status.items() if not has_value}
    missing = [name for name in GENERATED if name not in status]
    if empty:
        text, _ = _fill_empty_lines(env.read_text(encoding="utf-8"), empty)
        _write_private(env, text)
    if missing:
        _append(env, missing)
    return [name for name in GENERATED if name in empty or name in missing]


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    filled = init_env(root)
    print(f".env ready ({', '.join(filled)} generated)" if filled else ".env ready")
    if "POSTGRES_PASSWORD" in filled and (root / ".env").exists():
        print(
            "note: if the Postgres volume already exists it still holds the old password; "
            "run `make rotate-db-password` before `make up` (docs/runbook.md, Security)"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
