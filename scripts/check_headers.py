#!/usr/bin/env python3
"""Checks that every source file starts with the header comment (1-3 sentences
saying what the file does and where it fits). Hardened for M0.6: per-language parsing,
generated/lockfile/migration skip rules, and a `paths` / `--all` (git ls-files) CLI for
pre-commit and CI (`scripts/verify_m0.sh`)."""

from __future__ import annotations

import argparse
import ast
import re
import subprocess
import sys
from pathlib import Path

# Extensions the header rule applies to. Bare filenames are handled separately
# below (Dockerfile has variants like Dockerfile.dev; Makefile does not).
CHECKED_SUFFIXES = {
    ".py",
    ".ts",
    ".tsx",
    ".js",
    ".mjs",
    ".cjs",
    ".sh",
    ".sql",
    ".yaml",
    ".yml",
    ".toml",
}

# Comment-style groupings used by check_file.
_HASH_HEADER_SUFFIXES = {".sh", ".sql", ".yaml", ".yml", ".toml"}
_TS_JS_SUFFIXES = {".ts", ".tsx", ".js", ".mjs", ".cjs"}

# Directories whose contents are never checked: build output, dependencies, caches.
SKIP_DIR_PARTS = {
    "node_modules",
    ".next",
    "dist",
    "build",
    "__pycache__",
    ".venv",
    "venv",
    ".git",
    ".mypy_cache",
    ".ruff_cache",
    ".pytest_cache",
    "htmlcov",
    ".turbo",
    # Claude Code agents, rules and vendored skills (the cloud-session kit), not product code.
    ".claude",
}

# Individual files that are generated or otherwise exempt (lockfiles, generated types).
SKIP_FILE_NAMES = {
    "uv.lock",
    "pnpm-lock.yaml",
    "package-lock.json",
    "yarn.lock",
    "next-env.d.ts",
}

# Suffixes never checked, regardless of anything else (markdown, data/config formats
# that aren't source, and files handled by SKIP_FILE_NAMES / SKIP_DIR_PARTS instead).
SKIP_SUFFIXES = {".md", ".json"}

# Marker string alembic writes into every autogenerated migration's module docstring;
# those files are generated and exempt even though they live under `db/migrations` as .py.
_ALEMBIC_MARKER = "Revision ID:"

MIN_HEADER_CHARS = 15  # a real 1-3 sentence header is longer than this

# Directives that must stay on the very first line(s) of a file for the interpreter or
# parser (shebang, Docker syntax pragma) or that precede a Python docstring (PEP 263
# encoding declaration). The header comment/docstring is allowed to follow these.
_SHEBANG_RE = re.compile(r"^#!")
_DOCKER_SYNTAX_RE = re.compile(r"^#\s*syntax\s*=", re.IGNORECASE)
_ENCODING_RE = re.compile(r"^#.*coding[:=]\s*[-\w.]+")


def _is_dockerfile_name(name: str) -> bool:
    """Matches `Dockerfile`, `Dockerfile.dev`, `Dockerfile.prod`, etc.."""
    return name == "Dockerfile" or name.startswith("Dockerfile.")


def is_skipped(path: Path) -> bool:
    if path.name in SKIP_FILE_NAMES:
        return True
    if any(part in SKIP_DIR_PARTS for part in path.parts):
        return True
    return path.suffix in SKIP_SUFFIXES


def is_checked(path: Path) -> bool:
    if is_skipped(path):
        return False
    if (
        path.suffix in CHECKED_SUFFIXES
        or path.name in {"Makefile"}
        or _is_dockerfile_name(path.name)
    ):
        return not _is_alembic_autogen(path)
    return False


def _is_alembic_autogen(path: Path) -> bool:
    """Skips generated Alembic migrations (`db/migrations/...`) that carry the standard
    Alembic revision docstring instead of a header."""
    if path.suffix != ".py" or "migrations" not in path.parts:
        return False
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return _ALEMBIC_MARKER in text


def _strip_leading_directives(lines: list[str]) -> list[str]:
    """Drops a leading shebang, Docker `# syntax=` pragma, or PEP 263 encoding line
    before looking for the header comment (allows these to precede it)."""
    while lines:
        stripped = lines[0].strip()
        if (
            _SHEBANG_RE.match(stripped)
            or _DOCKER_SYNTAX_RE.match(stripped)
            or _ENCODING_RE.match(stripped)
        ):
            lines = lines[1:]
            continue
        break
    return lines


def has_hash_header(text: str) -> bool:
    """Shell, SQL, YAML, TOML, Dockerfile, Makefile: `#` comment header."""
    lines = _strip_leading_directives(text.splitlines())
    body = ""
    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        if not stripped.startswith("#"):
            return False
        body += stripped.lstrip("#").strip() + " "
        if len(body) >= MIN_HEADER_CHARS:
            return True
        continue
    return len(body.strip()) >= MIN_HEADER_CHARS


def has_python_header(path: Path) -> bool:
    """Python: a module docstring is the header. A leading encoding comment
    or shebang before the docstring is fine; ast.get_docstring ignores them."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return False
    doc = ast.get_docstring(tree)
    return doc is not None and len(doc.strip()) >= MIN_HEADER_CHARS


def has_ts_js_header(text: str) -> bool:
    """TS/TSX/JS/MJS/CJS: a leading `/** ... */` or `//` comment header."""
    lines = [line for line in text.splitlines() if line.strip()]
    if not lines:
        return False
    first = lines[0].strip()
    if first.startswith("/**") or first.startswith("/*"):
        collected = []
        for line in lines:
            collected.append(line.strip().strip("/*").strip())
            if "*/" in line:
                break
        return len(" ".join(collected).strip()) >= MIN_HEADER_CHARS
    if first.startswith("//"):
        collected = []
        for line in lines:
            stripped = line.strip()
            if not stripped.startswith("//"):
                break
            collected.append(stripped.lstrip("/").strip())
        return len(" ".join(collected).strip()) >= MIN_HEADER_CHARS
    return False


def check_file(path: Path) -> str | None:
    """Returns a per-file error message if `path` is missing its header, else None."""
    if path.suffix == ".py":
        if not has_python_header(path):
            return (
                f"{path}: missing module docstring header "
                "(1-3 sentences: what this file does and where it fits)"
            )
        return None
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return f"{path}: could not read as UTF-8 text"
    if path.suffix in _TS_JS_SUFFIXES:
        if not has_ts_js_header(text):
            return (
                f"{path}: missing leading `/** ... */` or `//` header comment "
                "(1-3 sentences: what this file does and where it fits)"
            )
        return None
    if not has_hash_header(text):
        return (
            f"{path}: missing leading `#` comment header "
            "(1-3 sentences: what this file does and where it fits)"
        )
    return None


def git_ls_files(root: Path) -> list[Path]:
    """Returns every git-tracked file under `root`, for `--all` mode
    (CI runs the header check over the whole tracked tree, not just the diff)."""
    result = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=root,
        capture_output=True,
        check=True,
    )
    names = result.stdout.decode("utf-8").split("\0")
    return [root / name for name in names if name]


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Checks source files for the PRD §8 file header comment."
    )
    parser.add_argument("paths", nargs="*", help="Specific files to check.")
    parser.add_argument(
        "--all",
        action="store_true",
        help="Check every git-tracked file (git ls-files) instead of explicit paths.",
    )
    return parser.parse_args(argv)


def iter_targets(args: argparse.Namespace, root: Path) -> list[Path]:
    if args.all or not args.paths:
        return git_ls_files(root)
    return [Path(p) for p in args.paths]


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parents[1]
    args = parse_args(argv)
    errors = []
    for path in iter_targets(args, root):
        if not path.is_file() or not is_checked(path):
            continue
        error = check_file(path)
        if error:
            errors.append(error)
    if errors:
        sys.stderr.write("Missing PRD §8 file headers:\n")
        for error in errors:
            sys.stderr.write(f"  - {error}\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
