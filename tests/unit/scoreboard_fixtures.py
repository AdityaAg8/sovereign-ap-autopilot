def write_reports(directory: Path, reports: dict[str, str] | None = None) -> Path:
    """Writes the fixture reports (or `reports`) into `directory` and returns it."""
    directory.mkdir(parents=True, exist_ok=True)
    for name, text in (ALL_REPORTS if reports is None else reports).items():
        (directory / name).write_text(text, encoding="utf-8")
    return directory


def fixed_commit_time(_path: Path) -> datetime:
    return COMMIT_TIME
