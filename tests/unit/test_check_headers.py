"""Unit tests for scripts/check_headers.py: header detection per language, the skip
rules for lockfiles/generated output/markdown/json/migrations, and the paths/--all
CLI (PRD §8, §10 M0.2, M0.6)."""

import importlib.util
import subprocess
from pathlib import Path
from types import ModuleType

_SPEC_PATH = Path(__file__).resolve().parents[2] / "scripts" / "check_headers.py"
_spec = importlib.util.spec_from_file_location("check_headers", _SPEC_PATH)
assert _spec is not None and _spec.loader is not None
ch: ModuleType = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ch)


def write(tmp_path: Path, name: str, content: str) -> Path:
    path = tmp_path / name
    path.write_text(content, encoding="utf-8")
    return path


def test_python_file_with_docstring_passes(tmp_path: Path) -> None:
    path = write(tmp_path, "mod.py", '"""Does one thing and fits somewhere specific."""\nx = 1\n')
    assert ch.check_file(path) is None


def test_python_file_without_docstring_fails(tmp_path: Path) -> None:
    path = write(tmp_path, "mod.py", "x = 1\n")
    assert ch.check_file(path) is not None


def test_shell_file_with_hash_header_passes(tmp_path: Path) -> None:
    path = write(
        tmp_path,
        "run.sh",
        "#!/usr/bin/env bash\n# Runs the thing that needs running for this purpose.\necho hi\n",
    )
    assert ch.check_file(path) is None


def test_shell_file_without_header_fails(tmp_path: Path) -> None:
    path = write(tmp_path, "run.sh", "#!/usr/bin/env bash\necho hi\n")
    assert ch.check_file(path) is not None


def test_ts_file_with_block_comment_passes(tmp_path: Path) -> None:
    path = write(tmp_path, "mod.ts", "/** Renders the widget for the review page. */\nexport {};\n")
    assert ch.check_file(path) is None


def test_ts_file_without_comment_fails(tmp_path: Path) -> None:
    path = write(tmp_path, "mod.ts", "export const x = 1;\n")
    assert ch.check_file(path) is not None


def test_markdown_is_skipped(tmp_path: Path) -> None:
    path = write(tmp_path, "NOTES.md", "no header needed\n")
    assert ch.is_checked(path) is False


def test_lockfile_is_skipped(tmp_path: Path) -> None:
    path = write(tmp_path, "uv.lock", "generated\n")
    assert ch.is_checked(path) is False


def test_node_modules_is_skipped(tmp_path: Path) -> None:
    nested = tmp_path / "node_modules" / "pkg.js"
    nested.parent.mkdir(parents=True)
    nested.write_text("no header\n", encoding="utf-8")
    assert ch.is_checked(nested) is False


def test_main_returns_nonzero_on_missing_header(tmp_path: Path) -> None:
    path = write(tmp_path, "mod.py", "x = 1\n")
    assert ch.main([str(path)]) == 1


def test_main_returns_zero_on_good_header(tmp_path: Path) -> None:
    path = write(tmp_path, "mod.py", '"""Does one thing and fits somewhere specific."""\n')
