"""`scripts/init_env.py`: first run copies `.env.example` and generates the empty secrets; later
runs append only missing keys, fill only empty ones, never touch a value that is already set and
never print a value."""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path
from types import ModuleType

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / "scripts" / "init_env.py"
GENERATED = ("API_JWT_SECRET", "POSTGRES_PASSWORD", "AGENT_RO_PASSWORD", "PARSE_SERVICE_TOKEN")


def _module() -> ModuleType:
    spec = importlib.util.spec_from_file_location("init_env", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _values(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        key, sep, value = line.partition("=")
        if sep and not key.startswith("#"):
            out[key.strip()] = value
    return out


def test_the_generated_set_covers_every_compose_secret() -> None:
    assert tuple(_module().GENERATED) == GENERATED


def test_first_run_generates_every_secret_and_later_runs_keep_them(tmp_path: Path) -> None:
    init_env = _module().init_env
    (tmp_path / ".env.example").write_text(
        "# comment\nAPI_JWT_SECRET=\nPOSTGRES_USER=\nPOSTGRES_PASSWORD=\nPOSTGRES_DB=\n"
    )
    assert init_env(tmp_path) == list(GENERATED)
    first = (tmp_path / ".env").read_text()
    values = _values(first)
    for name in GENERATED:
        assert re.fullmatch(r"[A-Za-z0-9_-]{40,}", values[name]), name
    assert len({values[name] for name in GENERATED}) == len(GENERATED)
    assert "# comment" in first and "POSTGRES_DB=" in first
    # Filled in place, not duplicated.
    assert first.count("POSTGRES_PASSWORD=") == 1 and first.count("API_JWT_SECRET=") == 1
    assert init_env(tmp_path) == []
    assert (tmp_path / ".env").read_text() == first


def test_missing_keys_are_appended_and_existing_lines_stay_byte_identical(
    tmp_path: Path,
) -> None:
    init_env = _module().init_env
    original = "POSTGRES_DB=apx\r\nAPI_JWT_SECRET=keep-me-exactly\r\nHF_TOKEN=hf_x"  # no final EOL
    (tmp_path / ".env").write_bytes(original.encode())
    assert init_env(tmp_path) == ["POSTGRES_PASSWORD", "AGENT_RO_PASSWORD", "PARSE_SERVICE_TOKEN"]
    after = (tmp_path / ".env").read_bytes().decode()
    assert after.startswith(original + "\n# Generated by scripts/init_env.py")
    values = _values(after.replace("\r", ""))
    assert values["API_JWT_SECRET"] == "keep-me-exactly"
    assert values["POSTGRES_PASSWORD"] and values["AGENT_RO_PASSWORD"]
    assert init_env(tmp_path) == []
    assert (tmp_path / ".env").read_bytes().decode() == after


@pytest.mark.parametrize("empty", ["", '""', "''", "   "])
def test_an_empty_or_quoted_empty_secret_is_filled_in_place(tmp_path: Path, empty: str) -> None:
    init_env = _module().init_env
    (tmp_path / ".env").write_text(
        f"POSTGRES_PASSWORD={empty}\nAPI_JWT_SECRET=set\nAGENT_RO_PASSWORD=set-too\n"
        "PARSE_SERVICE_TOKEN=set-3\nTAIL=1\n"
    )
    assert init_env(tmp_path) == ["POSTGRES_PASSWORD"]
    lines = (tmp_path / ".env").read_text().splitlines()
    assert lines[0].startswith("POSTGRES_PASSWORD=") and len(lines[0]) > 40
    assert lines[1:] == [
        "API_JWT_SECRET=set",
        "AGENT_RO_PASSWORD=set-too",
        "PARSE_SERVICE_TOKEN=set-3",
        "TAIL=1",
    ]


def test_export_prefixed_and_duplicate_keys_count_as_set(tmp_path: Path) -> None:
    init_env = _module().init_env
    text = "export API_JWT_SECRET=a\nPOSTGRES_PASSWORD=\nPOSTGRES_PASSWORD=b\nAGENT_RO_PASSWORD=c\n"
    text += "PARSE_SERVICE_TOKEN=d\n"
    (tmp_path / ".env").write_text(text)
    assert init_env(tmp_path) == []
    assert (tmp_path / ".env").read_text() == text


def test_main_reports_only_key_names(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    module = _module()
    (tmp_path / ".env").write_text("API_JWT_SECRET=existing-secret-value\n")
    # main() resolves the repo root from its own path; point it at tmp_path.
    monkeypatch.setattr(module, "__file__", str(tmp_path / "scripts" / "init_env.py"))
    assert module.main() == 0
    printed = capsys.readouterr().out
    assert "POSTGRES_PASSWORD" in printed and "AGENT_RO_PASSWORD" in printed
    for value in _values((tmp_path / ".env").read_text()).values():
        assert value not in printed
    assert "existing-secret-value" not in printed


def test_secret_key_status_exposes_only_booleans(tmp_path: Path) -> None:
    status = _module().secret_key_status
    (tmp_path / ".env").write_text("API_JWT_SECRET=x\nPOSTGRES_PASSWORD=\nOTHER=y\n")
    assert status(tmp_path / ".env") == {"API_JWT_SECRET": True, "POSTGRES_PASSWORD": False}


def test_missing_template_raises(tmp_path: Path) -> None:
    with pytest.raises(FileNotFoundError):
        _module().init_env(tmp_path)
